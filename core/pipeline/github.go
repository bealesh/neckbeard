package pipeline

import (
	"fmt"
	"strings"
)

const generatedYAMLHeader = "# Generated by neckbeard — do not edit. Regeneration refuses modified files;\n# change neckbeard.yaml or app-profile.yaml and re-run plan + scaffold.\n# The test hook (.neckbeard/hooks/test.sh) is yours and never regenerated.\n"

// RenderGitHubCI emits the app workflow: test on every PR/push; build, scan, and
// push (immutable tag, dev registry) on the default branch. Promotion moves the
// digest, never rebuilds (DESIGN §11.2).
func RenderGitHubCI(m Model) []byte {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }

	w("%s", generatedYAMLHeader)
	w("name: neckbeard-ci")
	w("")
	w("on:")
	w("  pull_request:")
	w("  push:")
	w("    branches: [%s]", m.DefaultBranch)
	w("")
	w("permissions:")
	w("  contents: read")
	w("")
	w("env:")
	w("  AWS_REGION: %s", m.Region)
	w("")
	w("jobs:")
	w("  test:")
	w("    runs-on: ubuntu-latest")
	w("    steps:")
	w("      - uses: actions/checkout@v4")
	w("      - name: Run test hook")
	w("        run: ./.neckbeard/hooks/test.sh")
	w("")
	w("  build:")
	w("    # Build once on %s; every environment runs this image by digest.", m.DefaultBranch)
	w("    if: github.event_name == 'push' && github.ref == 'refs/heads/%s'", m.DefaultBranch)
	w("    needs: [test]")
	w("    runs-on: ubuntu-latest")
	w("    environment: dev")
	w("    permissions:")
	w("      contents: read")
	w("      id-token: write # OIDC federation — no static cloud keys (DESIGN §10.1)")
	w("    env:")
	w("      REGISTRY: ${{ vars.%s_DEV }}", VarRegistry)
	w("    steps:")
	w("      - uses: actions/checkout@v4")
	w("      - name: Check bootstrap")
	w("        id: bootstrap")
	w("        run: |")
	w("          if [ -z \"$REGISTRY\" ]; then")
	w("            echo \"::warning::%s_DEV is not set (bootstrap pending) — build runs, push is skipped\"", VarRegistry)
	w("            echo \"push=false\" >> \"$GITHUB_OUTPUT\"")
	w("          else")
	w("            echo \"push=true\" >> \"$GITHUB_OUTPUT\"")
	w("          fi")
	w("      - name: Federate to AWS (dev)")
	w("        if: steps.bootstrap.outputs.push == 'true'")
	w("        uses: aws-actions/configure-aws-credentials@v4")
	w("        with:")
	w("          role-to-assume: ${{ vars.%s_DEV }}", VarApplyRole)
	w("          aws-region: ${{ env.AWS_REGION }}")
	w("      - name: Build image")
	w("        run: docker build -f %s -t \"neckbeard-build:${GITHUB_SHA}\" .", m.Dockerfile)
	w("      - name: Scan image (HIGH/CRITICAL block the merge gate)")
	w("        run: |")
	w("          docker run --rm -v /var/run/docker.sock:/var/run/docker.sock \\")
	w("            aquasec/trivy image --severity HIGH,CRITICAL --exit-code 1 \"neckbeard-build:${GITHUB_SHA}\"")
	w("      - name: Push (immutable tag; promotion moves digests, never rebuilds)")
	w("        if: steps.bootstrap.outputs.push == 'true'")
	w("        run: |")
	w("          aws ecr get-login-password --region \"$AWS_REGION\" | docker login --username AWS --password-stdin \"${REGISTRY%%%%/*}\"")
	w("          docker tag \"neckbeard-build:${GITHUB_SHA}\" \"${REGISTRY}:${GITHUB_SHA}\"")
	w("          docker push \"${REGISTRY}:${GITHUB_SHA}\"")
	w("          echo \"Pushed digest:\"")
	w("          docker inspect --format='{{index .RepoDigests 0}}' \"${REGISTRY}:${GITHUB_SHA}\"")
	return []byte(b.String())
}

// RenderGitHubInfra emits the infra workflow: per-env validate + plan on PRs,
// apply on the default branch. prd binds to the "prd" environment — required
// reviewers enforce there on plans that support it (private repos: Enterprise);
// the universal fallback is the protected default branch itself (DESIGN §11.3).
func RenderGitHubInfra(m Model) []byte {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }

	w("%s", generatedYAMLHeader)
	w("name: neckbeard-infra")
	w("")
	w("on:")
	w("  pull_request:")
	w("    paths: [\"infra/**\"]")
	w("  push:")
	w("    branches: [%s]", m.DefaultBranch)
	w("    paths: [\"infra/**\"]")
	w("")
	w("permissions:")
	w("  contents: read")
	w("")
	w("env:")
	w("  AWS_REGION: %s", m.Region)
	w("")
	w("jobs:")
	for _, env := range m.Envs {
		envUpper := strings.ToUpper(env)
		w("  infra-%s:", env)
		w("    runs-on: ubuntu-latest")
		w("    environment: %s", env)
		w("    permissions:")
		w("      contents: read")
		w("      id-token: write")
		w("    steps:")
		w("      - uses: actions/checkout@v4")
		w("      - uses: opentofu/setup-opentofu@v1")
		w("        with:")
		w("          tofu_version: %s # pinned by the blueprint", m.TofuVersion)
		w("      - name: Static validate (V0)")
		w("        run: |")
		w("          tofu -chdir=infra/envs/%s init -backend=false -input=false", env)
		w("          tofu -chdir=infra/envs/%s validate", env)
		w("      - name: Federate to AWS (%s) — plan role on PRs, apply role on %s", env, m.DefaultBranch)
		w("        if: vars.%s_%s != ''", VarPlanRole, envUpper)
		w("        uses: aws-actions/configure-aws-credentials@v4")
		w("        with:")
		w("          role-to-assume: ${{ github.event_name == 'push' && vars.%s_%s || vars.%s_%s }}", VarApplyRole, envUpper, VarPlanRole, envUpper)
		w("          aws-region: ${{ env.AWS_REGION }}")
		w("      - name: Plan, and apply on %s (V1; needs bootstrap backend config)", m.DefaultBranch)
		w("        run: |")
		w("          if [ ! -f infra/envs/%s/backend.hcl ] || [ -z \"${{ vars.%s_%s }}\" ]; then", env, VarPlanRole, envUpper)
		w("            echo \"::warning::bootstrap pending for %s (backend.hcl or CI roles missing) — validate-only run; plan/apply NOT EXERCISED\"", env)
		w("            exit 0")
		w("          fi")
		w("          tofu -chdir=infra/envs/%s init -reconfigure -input=false -backend-config=backend.hcl", env)
		w("          tofu -chdir=infra/envs/%s plan -input=false -out=tfplan", env)
		w("          if [ \"$GITHUB_EVENT_NAME\" = \"push\" ]; then")
		w("            tofu -chdir=infra/envs/%s apply -input=false tfplan", env)
		w("          fi")
		w("")
	}
	return []byte(strings.TrimRight(b.String(), "\n") + "\n")
}
