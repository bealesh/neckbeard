// Package disco renders an app profile for Disco (https://disco.cloud), an open
// source self-hosted PaaS: a disco.json for the repository plus a runbook of the
// one-time disco CLI commands. Like the cloud renderers it is a pure function of
// its input; unlike them it starts from the reviewed app profile rather than a
// blueprint, because a Disco server is the whole runtime (no modules to choose).
//
// Prototype for https://github.com/bealesh/neckbeard/issues/33.
package disco

import (
	"bytes"
	"encoding/json"
	"fmt"
	"regexp"
	"strings"

	"github.com/bealesh/neckbeard/core/profile"
)

// File mirrors the subset of disco.json the renderer writes.
// Field names and defaults: disco-daemon disco/utils/discofile.py.
type File struct {
	Version  string             `json:"version"`
	Services map[string]Service `json:"services"`
	Images   map[string]Image   `json:"images"`
}

type Service struct {
	Type     string `json:"type,omitempty"`
	Image    string `json:"image,omitempty"`
	Port     int    `json:"port,omitempty"`
	Command  string `json:"command,omitempty"`
	Schedule string `json:"schedule,omitempty"`
}

type Image struct {
	Dockerfile string `json:"dockerfile"`
	Context    string `json:"context"`
}

type Output struct {
	DiscoJSON []byte
	Runbook   []byte
}

// Render maps a planning-ready profile onto Disco. project is the Disco project name.
func Render(p *profile.AppProfile, project string) (Output, error) {
	if err := profile.Ready(p); err != nil {
		return Output{}, err
	}
	if !projectName.MatchString(project) {
		return Output{}, fmt.Errorf("project name %q: lowercase letters, digits and dashes, starting with a letter, at most 42 characters", project)
	}

	f := File{Version: "1.0", Services: map[string]Service{}, Images: map[string]Image{}}
	var web *profile.Service
	for i, s := range p.Services {
		if s.Name == "web" && s.Kind != "http" {
			return Output{}, fmt.Errorf("service named web is a %s: Disco reserves web for HTTP traffic; rename it", s.Kind)
		}
		f.Images["default"] = Image{Dockerfile: s.Dockerfile, Context: "."}
		svc := Service{Image: "default", Command: shellJoin(s.Command)}
		name := s.Name
		switch s.Kind {
		case "http":
			// Disco sends a project's HTTP traffic to its service named "web".
			if web != nil {
				return Output{}, fmt.Errorf("services %s and %s are both http: Disco routes one web service per project; render the second as its own project", web.Name, s.Name)
			}
			web = &p.Services[i]
			name = "web"
			svc.Port = s.Port
		case "worker":
		case "cron":
			svc.Type = "cron"
			svc.Schedule = s.Schedule
			if svc.Command == "" {
				return Output{}, fmt.Errorf("cron %s: Disco runs a cron's command; set command in the profile", s.Name)
			}
		default:
			return Output{}, fmt.Errorf("service %s: kind %q has no Disco mapping", s.Name, s.Kind)
		}
		f.Services[name] = svc
	}
	if web == nil {
		return Output{}, fmt.Errorf("no http service: a Disco project without a web service has nothing to route (workers-only projects need --no-domain, not rendered yet)")
	}

	var data bytes.Buffer
	enc := json.NewEncoder(&data)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(f); err != nil {
		return Output{}, err
	}

	rb, err := runbook(p, project, web)
	if err != nil {
		return Output{}, err
	}
	return Output{DiscoJSON: data.Bytes(), Runbook: rb}, nil
}

var projectName = regexp.MustCompile(`^[a-z][a-z0-9-]{0,41}$`)

func runbook(p *profile.AppProfile, project string, web *profile.Service) ([]byte, error) {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }
	w("# Deploy %s on Disco", project)
	w("")
	w("> Generated by neckbeard from app-profile.yaml. One time, by a human, with the disco CLI")
	w("> connected to a Disco server (https://disco.cloud/docs/). The agent never runs these.")
	w("")
	w("## 1. Create the project")
	w("")
	w("```sh")
	w("disco projects:add --name %s", project)
	w("```")
	w("")
	w("Without `--domain`, the project gets `%s.<your disco host>` when the server's host has a", project)
	w("wildcard DNS record (every host given by Disco's installer does).")
	w("")

	w("## 2. Datastores and secrets")
	w("")
	set := map[string]bool{}
	var envLines []string
	for _, n := range p.Needs {
		switch {
		case n.Capability == "postgres" && n.Mode == "provision":
			env := n.SecretName
			if env == "" {
				env = "DATABASE_URL"
			}
			w("Postgres on the Disco server (the Postgres addon; data on this server's disk, back it up):")
			w("")
			w("```sh")
			if env == "DATABASE_URL" {
				w("disco postgres:create --project %s", project)
			} else {
				w("disco postgres:create --project %s --env-var %s", project, env)
			}
			w("```")
			w("")
			set[env] = true
		case n.Mode == "reference":
			envLines = append(envLines, fmt.Sprintf("%s=<connection for the existing %s>", n.SecretName, n.Capability))
			set[n.SecretName] = true
		case n.Capability == "secrets":
			// Disco stores env vars encrypted at rest; secrets become env vars below.
		default:
			return nil, fmt.Errorf("%s with mode %s: no Disco mapping yet (named, not invented)", n.Capability, n.Mode)
		}
	}
	for _, s := range p.Secrets {
		if !set[s.Name] {
			envLines = append(envLines, s.Name+"=<value>")
			set[s.Name] = true
		}
	}
	if len(envLines) > 0 {
		w("Environment variables (values never go in the repository):")
		w("")
		w("```sh")
		w("disco env:set --project %s %s", project, strings.Join(envLines, " "))
		w("```")
		w("")
	}

	w("## 3. Deploy")
	w("")
	w("From the repository root (disco.json is there):")
	w("")
	w("```sh")
	w("disco deploy --project %s --dir .", project)
	w("```")
	w("")
	w("Or connect GitHub once (`disco github:apps:add`) and add the project with `--github <owner/repo>`:")
	w("every push to main or master (or the branch given with `--branch`) then deploys.")
	w("")
	w("## Notes")
	w("")
	w("- `web` must listen on 0.0.0.0:%d. Disco waits for that port before switching traffic; it does", web.Port)
	w("  not call %s itself (a disco.json `health` command runs inside the container instead).", web.HealthPath)
	w("- Cron schedules run in UTC.")
	w("- Logs: `disco logs --project %s`. Deployments: `disco deploy:list --project %s`.", project, project)
	return []byte(b.String()), nil
}

// shellJoin quotes a command for Disco, which splits `command` with shlex.
func shellJoin(args []string) string {
	out := make([]string, len(args))
	for i, a := range args {
		if a != "" && safeArg.MatchString(a) {
			out[i] = a
		} else {
			out[i] = "'" + strings.ReplaceAll(a, "'", `'"'"'`) + "'"
		}
	}
	return strings.Join(out, " ")
}

var safeArg = regexp.MustCompile(`^[A-Za-z0-9_./:=@%+,-]+$`)
